const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const coversDir = path.join(process.cwd(), 'public', 'images', 'blog-covers');
fs.mkdirSync(coversDir, { recursive: true });

const MISSING_REMOTE_COVERS = [
  {
    slug: 'seo-content-vs-thought-leadership',
    url: 'https://i.postimg.cc/9Q2XXHMf/SEO-Thought-Leadership.jpg'
  },
  {
    slug: 'how-to-brief-graphic-designer',
    url: 'https://i.postimg.cc/FFjdpXPB/Abu-Qitmir-Labs-Design-Brief-Blueprint.png'
  },
  {
    slug: 'design-trends-2026',
    url: 'https://i.postimg.cc/L5K7zjJ3/Design-Trends-Lasting-vs-Dying.png'
  },
  {
    slug: 'design-systems-for-startups',
    url: 'https://i.postimg.cc/HnPS19gt/Neon-Design-System-Startup-Guide.png'
  },
  {
    slug: 'measure-marketing-roi-without-tracking',
    url: 'https://i.postimg.cc/7L09n4zn/Marketing-ROI-Without-Perfect-Attribution.png'
  },
  {
    slug: 'the-non-technical-founders-guide-to-software-ownership-ip-2026',
    url: 'https://i.postimg.cc/NGNQF3vh/Software-Ownership-IP-Guide.png'
  }
];

async function downloadAndConvert() {
  for (const item of MISSING_REMOTE_COVERS) {
    const hash = crypto.createHash('md5').update(item.url).digest('hex').slice(0, 8);
    const prefix = item.slug.slice(0, 60);
    const outFilename = `${prefix}-${hash}.webp`;
    const outPath = path.join(coversDir, outFilename);

    if (!fs.existsSync(outPath)) {
      console.log(`Downloading ${item.url} for ${item.slug}...`);
      const res = await fetch(item.url);
      if (!res.ok) {
        throw new Error(`Failed to fetch ${item.url}: ${res.status}`);
      }
      const arrBuf = await res.arrayBuffer();
      const tmpIn = path.join('/tmp', `cover-${hash}.img`);
      fs.writeFileSync(tmpIn, Buffer.from(arrBuf));

      execFileSync('convert', [
        tmpIn,
        '-resize', '1200x675>',
        '-quality', '86',
        outPath
      ]);
      fs.unlinkSync(tmpIn);
      console.log(`✓ Saved local WebP: /images/blog-covers/${outFilename}`);
    } else {
      console.log(`✓ Already exists: /images/blog-covers/${outFilename}`);
    }
  }

  // Now scan all files in public/images/blog-covers/*.webp
  const allWebpFiles = fs.readdirSync(coversDir).filter(f => f.endsWith('.webp'));

  // Load current localCoverImageMap.ts to preserve existing mappings
  const mapPath = path.join(process.cwd(), 'src/data/localCoverImageMap.ts');
  const mapContent = fs.readFileSync(mapPath, 'utf8');

  const slugMap = {};
  const remoteMap = {};

  for (const m of mapContent.matchAll(/"([^"]+)":\s*"(\/images\/blog-covers\/[^"]+)"/g)) {
    const key = m[1];
    const val = m[2];
    if (key.startsWith('http')) {
      remoteMap[key] = val;
    } else {
      slugMap[key] = val;
    }
  }

  // Add the 6 newly downloaded remote URLs
  for (const item of MISSING_REMOTE_COVERS) {
    const hash = crypto.createHash('md5').update(item.url).digest('hex').slice(0, 8);
    const prefix = item.slug.slice(0, 60);
    const localUrl = `/images/blog-covers/${prefix}-${hash}.webp`;
    remoteMap[item.url] = localUrl;
    slugMap[item.slug] = localUrl;
  }

  // Also match all 15 previously missing slugs to their exact files in public/images/blog-covers
  const staticPath = path.join(process.cwd(), 'src/data/staticBlogPosts.ts');
  let staticSrc = fs.readFileSync(staticPath, 'utf8');
  const allStaticKeys = [...staticSrc.matchAll(/STATIC_BLOG_POSTS\["([^"]+)"\]/g)].map(m => m[1]);

  for (const slug of allStaticKeys) {
    if (!slugMap[slug]) {
      const prefix60 = slug.slice(0, 60);
      const prefix50 = slug.slice(0, 50);
      const found =
        allWebpFiles.find(f => f.startsWith(slug + '-')) ||
        allWebpFiles.find(f => f.startsWith(prefix60 + '-')) ||
        allWebpFiles.find(f => f.startsWith(prefix50));
      if (found) {
        slugMap[slug] = `/images/blog-covers/${found}`;
      }
    }
  }

  // Write updated src/data/localCoverImageMap.ts with bulletproof resolveOptimizedCoverImage
  const remoteEntries = Object.entries(remoteMap)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`)
    .join(',\n');

  const slugEntries = Object.entries(slugMap)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`)
    .join(',\n');

  const newMapTs = `/**
 * Auto-generated by scripts/optimize-blog-images.cjs
 * Maps external postimg.cc URLs and blog slugs to pre-optimized local WebP assets
 * served directly from Vercel Edge CDN (/images/blog-covers/*.webp).
 */

export const REMOTE_TO_LOCAL_COVER_MAP: Record<string, string> = {
${remoteEntries}
};

export const SLUG_TO_LOCAL_COVER_MAP: Record<string, string> = {
${slugEntries}
};

export function resolveOptimizedCoverImage(url?: string, slug?: string): string {
  // 1. Always check SLUG_TO_LOCAL_COVER_MAP first if slug is provided
  if (slug) {
    const cleanSlug = slug.replace(/^\\/+/, '').replace(/^blog\\//, '').trim();
    if (SLUG_TO_LOCAL_COVER_MAP[cleanSlug]) {
      return SLUG_TO_LOCAL_COVER_MAP[cleanSlug];
    }
  }

  // 2. Check URL if it is not a generic logo.png placeholder
  if (url && typeof url === 'string') {
    const clean = url.trim();
    if (clean && !clean.includes('/logo.png')) {
      if (REMOTE_TO_LOCAL_COVER_MAP[clean]) {
        return REMOTE_TO_LOCAL_COVER_MAP[clean];
      }
      if (clean.startsWith('https://www.abuqitmirlabs.tech/')) {
        const rel = clean.replace('https://www.abuqitmirlabs.tech', '');
        if (REMOTE_TO_LOCAL_COVER_MAP[rel]) return REMOTE_TO_LOCAL_COVER_MAP[rel];
        return rel;
      }
      return clean;
    }
  }

  return url || '';
}
`;

  fs.writeFileSync(mapPath, newMapTs, 'utf8');
  console.log(`✓ Updated src/data/localCoverImageMap.ts with ${Object.keys(slugMap).length} slug mappings.`);

  // 3. Update staticBlogPosts.ts so any post with logo.png gets its real local WebP coverImage
  let staticUpdated = 0;
  staticSrc = staticSrc.replace(
    /STATIC_BLOG_POSTS\["([^"]+)"\]\s*=\s*\{([\s\S]*?)\n\};/g,
    (fullMatch, key, body) => {
      const localCover = slugMap[key];
      if (!localCover) return fullMatch;

      const updatedBody = body.replace(
        /"coverImage":\s*"([^"]+)"/,
        (m, oldCover) => {
          if (oldCover.includes('logo.png') || oldCover.includes('i.postimg.cc')) {
            staticUpdated++;
            return `"coverImage": "${localCover}"`;
          }
          return m;
        }
      );
      return `STATIC_BLOG_POSTS["${key}"] = {${updatedBody}\n};`;
    }
  );
  fs.writeFileSync(staticPath, staticSrc, 'utf8');
  console.log(`✓ Updated ${staticUpdated} coverImage entries in src/data/staticBlogPosts.ts`);

  // 4. Update content/blog/*.md frontmatter coverImage if it was logo.png or i.postimg.cc
  const mdDir = path.join(process.cwd(), 'content/blog');
  let mdUpdated = 0;
  if (fs.existsSync(mdDir)) {
    for (const file of fs.readdirSync(mdDir).filter(f => f.endsWith('.md'))) {
      const slug = file.replace(/\.md$/, '');
      const localCover = slugMap[slug];
      if (!localCover) continue;

      const fullPath = path.join(mdDir, file);
      const raw = fs.readFileSync(fullPath, 'utf8');
      const updated = raw.replace(
        /("coverImage"\s*:\s*")(https?:\/\/[^"]*logo\.png|\/logo\.png|https?:\/\/i\.postimg\.cc\/[^"]+)(")/,
        (_, p1, _old, p3) => {
          mdUpdated++;
          return `${p1}${localCover}${p3}`;
        }
      );
      if (updated !== raw) {
        fs.writeFileSync(fullPath, updated, 'utf8');
      }
    }
  }
  console.log(`✓ Updated ${mdUpdated} coverImage entries in content/blog/*.md`);

  // 5. Update seoRoutesMetadata.ts ogImage & twitterImage if they were logo.png for blog posts
  const seoPath = path.join(process.cwd(), 'src/data/seoRoutesMetadata.ts');
  let seoUpdated = 0;
  if (fs.existsSync(seoPath)) {
    let seoSrc = fs.readFileSync(seoPath, 'utf8');
    for (const [slug, localCover] of Object.entries(slugMap)) {
      const fullImgUrl = `https://www.abuqitmirlabs.tech${localCover}`;
      const escapedSlug = slug.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const blockRegex = new RegExp(`(["'](?:/blog)?/${escapedSlug}["']\\s*:\\s*\\{[\\s\\S]*?\\n\\s*\\})`, 'g');
      seoSrc = seoSrc.replace(blockRegex, (block) => {
        return block.replace(
          /((?:ogImage|twitterImage)\s*:\s*["'])(https:\/\/www\.abuqitmirlabs\.tech\/logo\.png|https?:\/\/i\.postimg\.cc\/[^"']+)(["'])/g,
          (_, p1, _old, p3) => {
            seoUpdated++;
            return `${p1}${fullImgUrl}${p3}`;
          }
        );
      });
    }
    fs.writeFileSync(seoPath, seoSrc, 'utf8');
  }
  console.log(`✓ Updated ${seoUpdated} ogImage/twitterImage entries in src/data/seoRoutesMetadata.ts`);
}

downloadAndConvert().catch(err => {
  console.error(err);
  process.exit(1);
});
