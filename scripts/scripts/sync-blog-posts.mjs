// scripts/sync-blog-posts.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const contentDir = path.join(rootDir, 'content', 'blog');

// 1. Content files ko scan karein
const files = fs.readdirSync(contentDir).filter(f => f.endsWith('.md'));
console.log(`📄 Found ${files.length} blog posts`);

const posts = [];

for (const file of files) {
  const content = fs.readFileSync(path.join(contentDir, file), 'utf-8');
  const fmMatch = content.match(/^---\n([\s\S]*?)\n---/);
  
  if (!fmMatch) {
    console.warn(`⚠️  No frontmatter in ${file}`);
    continue;
  }
  
  try {
    const meta = JSON.parse(fmMatch[1]);
    posts.push({
      slug: meta.slug,
      title: meta.title,
      excerpt: meta.excerpt,
      category: meta.category || 'Development',
      author: meta.author || 'AbuQitmirLabs',
      tags: meta.tags || [],
      publishedAt: meta.publishedAt,
      coverImage: meta.coverImage || 'https://www.abuqitmirlabs.tech/images/default-og.jpg',
      coverImageAlt: meta.coverImageAlt || meta.title,
      content: content.replace(/^---\n[\s\S]*?\n---\n/, '').trim()
    });
  } catch (e) {
    console.error(`❌ JSON parse error in ${file}:`, e.message);
  }
}

// 2. staticBlogPosts.ts generate karein
const staticPostsContent = `// AUTO-GENERATED by scripts/sync-blog-posts.mjs
// Do not edit manually. Edit content/blog/*.md instead.

export interface BlogPost {
  slug: string;
  title: string;
  excerpt: string;
  category: string;
  author: string;
  tags: string[];
  publishedAt: string;
  coverImage: string;
  coverImageAlt: string;
  content: string;
}

export const staticBlogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;

fs.writeFileSync(
  path.join(rootDir, 'src', 'data', 'staticBlogPosts.ts'),
  staticPostsContent
);
console.log(`✅ Generated staticBlogPosts.ts with ${posts.length} posts`);

// 3. seoRoutesMetadata.ts ke liye metadata generate karein
const seoMetadata = posts.map(post => ({
  path: `/blog/${post.slug}`,
  title: `${post.title} | AbuQitmirLabs`,
  description: post.excerpt.substring(0, 155),
  keywords: post.tags.join(', '),
  ogImage: post.coverImage,
  ogTitle: post.title,
  twitterTitle: post.title,
  twitterImage: post.coverImage
}));

const seoContent = `// AUTO-GENERATED by scripts/sync-blog-posts.mjs
// Do not edit manually.

export const blogSeoMetadata = ${JSON.stringify(seoMetadata, null, 2)};
`;

fs.writeFileSync(
  path.join(rootDir, 'src', 'data', 'blogSeoMetadata.ts'),
  seoContent
);
console.log(`✅ Generated blogSeoMetadata.ts with ${seoMetadata.length} entries`);

// 4. Sitemap generate karein
const baseUrl = 'https://www.abuqitmirlabs.tech';
const today = new Date().toISOString().split('T')[0];

let sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n';
sitemap += '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n';

// Static pages
const staticPages = [
  { url: '/', priority: '1.0', changefreq: 'weekly' },
  { url: '/custom-software', priority: '0.9', changefreq: 'monthly' },
  { url: '/web-development', priority: '0.9', changefreq: 'monthly' },
  { url: '/mobile-app-development', priority: '0.9', changefreq: 'monthly' },
  { url: '/ai-agent-development', priority: '0.9', changefreq: 'monthly' },
  { url: '/seo-mastery', priority: '0.9', changefreq: 'monthly' },
  { url: '/contact', priority: '0.8', changefreq: 'yearly' }
];

staticPages.forEach(p => {
  sitemap += `  <url><loc>${baseUrl}${p.url}</loc><changefreq>${p.changefreq}</changefreq><priority>${p.priority}</priority><lastmod>${today}</lastmod></url>\n`;
});

// Blog posts
posts.forEach(post => {
  sitemap += `  <url><loc>${baseUrl}/blog/${post.slug}</loc><changefreq>weekly</changefreq><priority>0.9</priority><lastmod>${post.publishedAt || today}</lastmod></url>\n`;
});

sitemap += '</urlset>\n';

fs.writeFileSync(path.join(rootDir, 'public', 'sitemap.xml'), sitemap);
console.log(`✅ Generated sitemap.xml with ${posts.length} blog posts`);
console.log(`\n🎉 Sync complete! ${posts.length} posts registered.`);